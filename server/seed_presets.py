def _import_demo_novels(conn, user_id, now):
    """从 data/seed_novels/*.json 导入演示小说。"""
    import uuid
    from pathlib import Path

    novel_dir = Path(__file__).resolve().parent.parent / "data" / "seed_novels"
    if not novel_dir.is_dir():
        print(f"  ⚠️ 小说数据目录不存在: {novel_dir}")
        return

    json_files = sorted(novel_dir.glob("*.json"))
    if not json_files:
        print("  ⚠️ 无小说 JSON 文件")
        return

    # world 名称 → world_id 映射
    worlds = {}
    for row in conn.execute(
        "SELECT world_id, name, description, world_history, rules FROM worlds WHERE is_deleted = 0"
    ):
        worlds[row["name"]] = dict(row)

    # world_id → characters 映射
    world_chars = {}
    for row in conn.execute(
        "SELECT world_id, character_id, name, identity, personality, speech_style, "
        "goal, attitudes, backstory, initial_location, initial_state, accent_color "
        "FROM world_characters"
    ):
        wid = row["world_id"]
        world_chars.setdefault(wid, []).append(dict(row))

    imported = 0
    for f in json_files:
        data = json.loads(f.read_text(encoding="utf-8"))
        name = data["name"]
        if name not in worlds:
            print(f"  ⚠️ 跳过: {name}（worlds 表中无匹配）")
            continue

        world = worlds[name]
        world_id = world["world_id"]

        # 检查 evolution 是否已存在
        existing_evo = conn.execute(
            "SELECT evolution_id FROM world_evolutions WHERE world_id = ? AND user_id = ?",
            (world_id, user_id),
        ).fetchone()
        if existing_evo:
            evolution_id = existing_evo["evolution_id"]
            print(f"  {name}: evolution 已存在 {evolution_id}")
        else:
            evolution_id = f"evo_{world_id}"
            conn.execute(
                "INSERT INTO world_evolutions "
                "(evolution_id, user_id, world_id, status, current_round, max_rounds, "
                "global_notify_count, director_context, character_contexts, timeline, relationships, "
                "is_deleted, created_at) "
                "VALUES (?, ?, ?, 'ended', 1, 20, 0, '[]', '{}', '[]', '{}', 1, ?)",
                (evolution_id, user_id, world_id, now),
            )

        # 检查 novel 是否已存在
        existing_novel = conn.execute(
            "SELECT novel_id FROM novels WHERE world_id = ? AND user_id = ? AND is_deleted = 0",
            (world_id, user_id),
        ).fetchone()
        if existing_novel:
            print(f"  {name}: novel 已存在 {existing_novel['novel_id']}，跳过")
            continue

        # world_snapshot
        world_snapshot = {
            "name": world["name"],
            "description": world["description"],
            "world_history": world.get("world_history", ""),
            "rules": world.get("rules", "[]"),
            "characters": world_chars.get(world_id, []),
        }

        # 写入 novel
        novel_id = f"novel_{uuid.uuid4().hex[:8]}"
        conn.execute(
            "INSERT INTO novels (novel_id, user_id, world_id, evolution_id, title, "
            "content, world_snapshot, is_deleted, created_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, 0, ?)",
            (novel_id, user_id, world_id, evolution_id, data["title"],
             data["content"], json.dumps(world_snapshot, ensure_ascii=False), now),
        )

        # 写入 novel_characters
        chars = world_chars.get(world_id, [])
        for wc in chars:
            char_id = f"nc_{uuid.uuid4().hex[:8]}"
            conn.execute(
                "INSERT OR REPLACE INTO novel_characters "
                "(character_id, novel_id, user_id, source_character_id, "
                "character_snapshot, story_context, accent_color, is_deleted, created_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, 0, ?)",
                (char_id, novel_id, user_id, wc["character_id"],
                 json.dumps(wc, ensure_ascii=False), "",
                 wc.get("accent_color", ""), now),
            )

        # 写入 novel_tasks
        task_id = f"task_{uuid.uuid4().hex[:8]}"
        conn.execute(
            "INSERT INTO novel_tasks (task_id, novel_id, evolution_id, status, "
            "created_at, completed_at) VALUES (?, ?, ?, 'completed', ?, ?)",
            (task_id, novel_id, evolution_id, now, now),
        )

        imported += 1
        print(f"  ✅ {name}: {data['chapter_count']} 章, {data['total_chars']} 字 → {novel_id}")

    print(f"\n📚 小说导入完成: {imported}/{len(json_files)}")


