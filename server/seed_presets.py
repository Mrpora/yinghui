"""
预设世界模板 + 演示小说一体化导入脚本。

独立运行，无外部包依赖：python3 seed_presets.py [user_id]
"""

import json
import os
import sqlite3


def _now_ms() -> int:
    from datetime import datetime, timezone
    return int(datetime.now(timezone.utc).timestamp() * 1000)


def _get_db(db_path: str) -> sqlite3.Connection:
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def _init_schema(conn: sqlite3.Connection):
    """创建全部 11 张表 + 向量表（幂等）。"""
    conn.executescript("""
        CREATE TABLE IF NOT EXISTS users (
            user_id     TEXT PRIMARY KEY,
            nickname    TEXT NOT NULL UNIQUE,
            created_at  INTEGER NOT NULL
        );
        CREATE TABLE IF NOT EXISTS worlds (
            world_id       TEXT PRIMARY KEY,
            user_id        TEXT NOT NULL REFERENCES users(user_id),
            name           TEXT NOT NULL,
            description    TEXT NOT NULL DEFAULT '',
            world_history  TEXT NOT NULL DEFAULT '',
            rules          TEXT NOT NULL DEFAULT '[]',
            initial_event  TEXT NOT NULL DEFAULT '{}',
            is_preset      INTEGER NOT NULL DEFAULT 0,
            is_deleted     INTEGER NOT NULL DEFAULT 0,
            created_at     INTEGER NOT NULL
        );
        CREATE INDEX IF NOT EXISTS idx_worlds_user ON worlds(user_id);
        CREATE INDEX IF NOT EXISTS idx_worlds_preset ON worlds(is_preset);

        CREATE TABLE IF NOT EXISTS world_characters (
            character_id     TEXT PRIMARY KEY,
            world_id         TEXT NOT NULL REFERENCES worlds(world_id),
            name             TEXT NOT NULL,
            identity         TEXT NOT NULL DEFAULT '',
            personality      TEXT NOT NULL DEFAULT '',
            speech_style     TEXT NOT NULL DEFAULT '',
            goal             TEXT NOT NULL DEFAULT '',
            attitudes        TEXT NOT NULL DEFAULT '{}',
            backstory        TEXT NOT NULL DEFAULT '',
            initial_location TEXT NOT NULL DEFAULT '',
            initial_state    TEXT NOT NULL DEFAULT '',
            accent_color     TEXT NOT NULL DEFAULT '',
            sort_order       INTEGER NOT NULL DEFAULT 0
        );

        CREATE TABLE IF NOT EXISTS world_evolutions (
            evolution_id       TEXT PRIMARY KEY,
            user_id            TEXT NOT NULL REFERENCES users(user_id),
            world_id           TEXT NOT NULL REFERENCES worlds(world_id),
            status             TEXT NOT NULL DEFAULT 'idle',
            current_round      INTEGER NOT NULL DEFAULT 0,
            max_rounds         INTEGER NOT NULL DEFAULT 20,
            global_notify_count INTEGER DEFAULT 0,
            director_context   TEXT NOT NULL DEFAULT '[]',
            character_contexts TEXT NOT NULL DEFAULT '{}',
            timeline           TEXT NOT NULL DEFAULT '[]',
            relationships      TEXT NOT NULL DEFAULT '{}',
            is_deleted         INTEGER NOT NULL DEFAULT 0,
            created_at         INTEGER NOT NULL
        );
        CREATE INDEX IF NOT EXISTS idx_evolutions_world ON world_evolutions(world_id);
        CREATE INDEX IF NOT EXISTS idx_evolutions_user ON world_evolutions(user_id);

        CREATE TABLE IF NOT EXISTS novels (
            novel_id       TEXT PRIMARY KEY,
            user_id        TEXT NOT NULL REFERENCES users(user_id),
            world_id       TEXT NOT NULL REFERENCES worlds(world_id),
            evolution_id   TEXT NOT NULL,
            title          TEXT NOT NULL,
            content        TEXT NOT NULL,
            world_snapshot TEXT NOT NULL,
            is_deleted     INTEGER NOT NULL DEFAULT 0,
            created_at     INTEGER NOT NULL
        );
        CREATE INDEX IF NOT EXISTS idx_novels_user ON novels(user_id);

        CREATE TABLE IF NOT EXISTS novel_tasks (
            task_id       TEXT PRIMARY KEY,
            novel_id      TEXT NOT NULL REFERENCES novels(novel_id),
            evolution_id  TEXT NOT NULL,
            status        TEXT NOT NULL DEFAULT 'processing',
            result        TEXT,
            error         TEXT,
            created_at    INTEGER NOT NULL,
            completed_at  INTEGER
        );

        CREATE TABLE IF NOT EXISTS novel_characters (
            character_id        TEXT PRIMARY KEY,
            novel_id            TEXT NOT NULL REFERENCES novels(novel_id),
            user_id             TEXT NOT NULL REFERENCES users(user_id),
            source_character_id TEXT NOT NULL,
            character_snapshot  TEXT NOT NULL,
            story_context       TEXT NOT NULL DEFAULT '',
            accent_color        TEXT NOT NULL DEFAULT '',
            is_deleted          INTEGER NOT NULL DEFAULT 0,
            created_at          INTEGER NOT NULL,
            UNIQUE (novel_id, source_character_id)
        );
        CREATE INDEX IF NOT EXISTS idx_novel_chars_novel ON novel_characters(novel_id);

        CREATE TABLE IF NOT EXISTS character_chats (
            chat_id       TEXT PRIMARY KEY,
            user_id       TEXT NOT NULL REFERENCES users(user_id),
            novel_id      TEXT NOT NULL REFERENCES novels(novel_id),
            character_id  TEXT NOT NULL REFERENCES novel_characters(character_id),
            messages      TEXT NOT NULL DEFAULT '[]',
            is_deleted    INTEGER NOT NULL DEFAULT 0,
            created_at    INTEGER NOT NULL,
            modified_at   INTEGER NOT NULL
        );
        CREATE INDEX IF NOT EXISTS idx_chats_user_char ON character_chats(user_id, character_id);

        CREATE TABLE IF NOT EXISTS memories (
            memory_id        TEXT PRIMARY KEY,
            user_id          TEXT NOT NULL REFERENCES users(user_id),
            novel_id         TEXT NOT NULL REFERENCES novels(novel_id),
            character_id     TEXT NOT NULL REFERENCES novel_characters(character_id),
            memory_type      TEXT NOT NULL CHECK(memory_type IN ('user_fact', 'event')),
            content          TEXT NOT NULL,
            keywords         TEXT,
            created_at       INTEGER NOT NULL,
            updated_at       INTEGER NOT NULL,
            expires_at       INTEGER,
            last_recalled_at INTEGER,
            recall_count     INTEGER DEFAULT 0
        );
        CREATE INDEX IF NOT EXISTS idx_memories_novel ON memories(novel_id);
        CREATE INDEX IF NOT EXISTS idx_memories_user_novel ON memories(user_id, novel_id);

        CREATE TABLE IF NOT EXISTS memory_bm25 (
            memory_id       TEXT NOT NULL REFERENCES memories(memory_id) ON DELETE CASCADE,
            token           TEXT NOT NULL,
            term_frequency  INTEGER NOT NULL,
            PRIMARY KEY (memory_id, token)
        );

        CREATE TABLE IF NOT EXISTS care_settings (
            user_id       TEXT NOT NULL REFERENCES users(user_id),
            novel_id      TEXT NOT NULL REFERENCES novels(novel_id),
            character_id  TEXT NOT NULL REFERENCES novel_characters(character_id),
            level         INTEGER DEFAULT 80,
            PRIMARY KEY (user_id, novel_id, character_id)
        );
    """)
    conn.commit()


def _upsert_user(conn: sqlite3.Connection, user_id: str) -> None:
    now = _now_ms()
    conn.execute(
        "INSERT OR IGNORE INTO users (user_id, nickname, created_at) VALUES (?, ?, ?)",
        (user_id, user_id, now),
    )
    conn.commit()


def _insert_world(conn, world_id, user_id, name, description, rules, initial_event, world_history, now):
    conn.execute(
        "INSERT OR IGNORE INTO worlds (world_id, user_id, name, description, world_history, rules, initial_event, is_preset, created_at) "
        "VALUES (?, ?, ?, ?, ?, ?, ?, 1, ?)",
        (world_id, user_id, name, description,
         world_history,
         json.dumps(rules, ensure_ascii=False),
         json.dumps(initial_event, ensure_ascii=False),
         now),
    )


# 与 server/storage/sqlite_client.py 的 _CHARACTER_PALETTE / _pick_accent_color
# 保持同步：调色板与选择算法（名字序数和哈希取色 + 线性探测避撞）在此刻意重复，
# 因 seed_presets 为 stdlib-only 独立脚本（无外部包依赖隔离），不得 import
# 服务端模块。同步锁定见 tests/test_palette_sync.py（W4a F4）。
_PALETTE = ["#7B9EFF", "#4ECDC4", "#FF6B5B", "#F5C842", "#B8835A", "#7B9A8E",
            "#E2805C", "#9B8E7E", "#C44B3A", "#8E7CC3", "#5F9EA0", "#D4A5A5"]


def _accent_color(name: str, used: set[str]) -> str:
    """根据角色名确定性生成主题色，同世界内线性探测避免冲突。

    与 server/storage/sqlite_client.py 的 _pick_accent_color 保持同步：
    算法刻意重复（见上方 _PALETTE 处注释）。
    """
    h = sum(ord(c) for c in name)
    idx = h % len(_PALETTE)
    offset = 0
    while _PALETTE[(idx + offset) % len(_PALETTE)] in used and offset < len(_PALETTE):
        offset += 1
    return _PALETTE[(idx + offset) % len(_PALETTE)]


def _insert_characters(conn, chars):
    assigned: set[str] = set()
    enriched = []
    for c in chars:
        c_list = list(c)
        # accent_color 在索引 11；若为空则根据角色名生成
        if not c_list[11]:
            c_list[11] = _accent_color(c_list[2], assigned)
        assigned.add(c_list[11])
        enriched.append(tuple(c_list))
    conn.executemany(
        "INSERT OR IGNORE INTO world_characters (character_id, world_id, name, identity, personality, "
        "speech_style, goal, attitudes, backstory, initial_location, initial_state, accent_color, sort_order) "
        "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        enriched,
    )


